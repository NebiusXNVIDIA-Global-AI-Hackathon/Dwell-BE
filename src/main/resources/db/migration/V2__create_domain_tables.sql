-- Assistant

CREATE TABLE conversation
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    type       VARCHAR(10) NOT NULL,
    case_id    BIGINT REFERENCES cases (id) ON DELETE CASCADE,
    created_at TIMESTAMP   NOT NULL
);

-- One conversation per case
CREATE UNIQUE INDEX uk_conversation_case ON conversation (case_id) WHERE type = 'CASE';

CREATE TABLE message
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT      NOT NULL REFERENCES conversation (id) ON DELETE CASCADE,
    role            VARCHAR(10) NOT NULL,
    content         TEXT        NOT NULL,
    citations       JSONB,
    cards           JSONB,
    quick_replies   JSONB,
    attachments     JSONB,
    created_at      TIMESTAMP   NOT NULL
);

CREATE TABLE assistant_action
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id BIGINT      NOT NULL UNIQUE REFERENCES message (id) ON DELETE CASCADE,
    type       VARCHAR(30) NOT NULL,
    choices    JSONB       NOT NULL,
    chosen     VARCHAR(20),
    payload    JSONB,
    created_at TIMESTAMP   NOT NULL
);

