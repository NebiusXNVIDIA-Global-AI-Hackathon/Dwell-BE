-- users: align with the ERD
ALTER TABLE users RENAME COLUMN password TO password_hash;
ALTER TABLE users ALTER COLUMN password_hash DROP NOT NULL;
ALTER TABLE users RENAME COLUMN created_date TO created_at;
ALTER TABLE users RENAME COLUMN modified_date TO modified_at;
ALTER TABLE users ALTER COLUMN created_at SET NOT NULL;
ALTER TABLE users ALTER COLUMN modified_at SET NOT NULL;
ALTER TABLE users ALTER COLUMN role TYPE VARCHAR(20);
ALTER TABLE users
    ADD COLUMN first_name         VARCHAR(50)  NOT NULL,
    ADD COLUMN last_name          VARCHAR(50)  NOT NULL,
    ADD COLUMN preferred_language VARCHAR(10)  NOT NULL,
    ADD COLUMN profile_image_key  VARCHAR(255),
    ADD COLUMN nickname           VARCHAR(30) UNIQUE,
    ADD COLUMN auth_provider      VARCHAR(10)  NOT NULL DEFAULT 'LOCAL',
    ADD COLUMN provider_id        VARCHAR(255),
    ADD CONSTRAINT uk_users_provider UNIQUE (auth_provider, provider_id);

CREATE TABLE refresh_token
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash VARCHAR(255) NOT NULL,
    expires_at TIMESTAMP    NOT NULL,
    revoked_at TIMESTAMP,
    created_at TIMESTAMP    NOT NULL
);

CREATE TABLE device
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    push_token VARCHAR(255) NOT NULL UNIQUE,
    platform   VARCHAR(20)  NOT NULL,
    created_at TIMESTAMP    NOT NULL
);

-- Building

CREATE TABLE building
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bbl           VARCHAR(10)  NOT NULL UNIQUE,
    street        VARCHAR(255) NOT NULL,
    city          VARCHAR(50)  NOT NULL,
    state         VARCHAR(2)   NOT NULL,
    zip           VARCHAR(10)  NOT NULL,
    hpd_synced_at TIMESTAMP,
    created_at    TIMESTAMP    NOT NULL
);

CREATE TABLE user_place
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT      NOT NULL UNIQUE REFERENCES users (id) ON DELETE CASCADE,
    building_id       BIGINT      NOT NULL REFERENCES building (id),
    unit              VARCHAR(20) NOT NULL,
    floor             INT,
    unit_line         VARCHAR(10),
    lease_in_own_name BOOLEAN     NOT NULL,
    landlord_name     VARCHAR(100),
    landlord_phone    VARCHAR(20),
    created_at        TIMESTAMP   NOT NULL,
    modified_at       TIMESTAMP   NOT NULL
);

CREATE TABLE hpd_violation
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    building_id      BIGINT       NOT NULL REFERENCES building (id),
    record_type      VARCHAR(20)  NOT NULL,
    hpd_violation_id VARCHAR(20)  NOT NULL,
    issue_type       VARCHAR(20)  NOT NULL,
    category         VARCHAR(100) NOT NULL,
    status           VARCHAR(10)  NOT NULL,
    violation_class  VARCHAR(2),
    reported_at      DATE         NOT NULL,
    closed_at        DATE,
    CONSTRAINT uk_hpd_violation_record UNIQUE (record_type, hpd_violation_id)
);

CREATE TABLE building_insight
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    building_id          BIGINT      NOT NULL UNIQUE REFERENCES building (id),
    avg_days_to_resolve  INT,
    avg_response_days    DECIMAL(4, 1),
    no_response_rate     INT,
    landlord_risk        VARCHAR(20),
    data_source          VARCHAR(20) NOT NULL,
    computed_at          TIMESTAMP   NOT NULL
);

CREATE TABLE building_signal
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    building_id       BIGINT      NOT NULL REFERENCES building (id),
    issue_category    VARCHAR(30) NOT NULL,
    scope             VARCHAR(30) NOT NULL,
    floor_from        INT,
    floor_to          INT,
    report_count      INT         NOT NULL,
    window_days       INT         NOT NULL,
    insight           JSONB,
    guided_inspection JSONB,
    confidence        VARCHAR(10),
    breakdown         JSONB,
    computed_at       TIMESTAMP   NOT NULL
);

-- Case

CREATE TABLE cases
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_number         VARCHAR(20)  NOT NULL,
    user_id             BIGINT       NOT NULL REFERENCES users (id),
    building_id         BIGINT REFERENCES building (id),
    unit                VARCHAR(20),
    title               VARCHAR(100) NOT NULL,
    issue_category      VARCHAR(30)  NOT NULL,
    issue_detail        VARCHAR(30)  NOT NULL,
    issue_detail_other  VARCHAR(50),
    issue_type          VARCHAR(20)  NOT NULL,
    location            VARCHAR(20)  NOT NULL,
    location_other      VARCHAR(50),
    sub_location        VARCHAR(20),
    affected_area       VARCHAR(20)  NOT NULL,
    severity            VARCHAR(10)  NOT NULL,
    stage               VARCHAR(30)  NOT NULL,
    visibility          VARCHAR(10)  NOT NULL DEFAULT 'PRIVATE',
    description         VARCHAR(500),
    safety_acknowledged BOOLEAN      NOT NULL DEFAULT FALSE,
    first_observed_at   DATE,
    resolved_at         TIMESTAMP,
    analysis_status     VARCHAR(10)  NOT NULL,
    ai_analysis         JSONB,
    summary             JSONB,
    summary_updated_at  TIMESTAMP,
    next_action_type    VARCHAR(30),
    next_action         JSONB,
    deleted_at          TIMESTAMP,
    created_at          TIMESTAMP    NOT NULL,
    modified_at         TIMESTAMP    NOT NULL,
    CONSTRAINT uk_cases_user_case_number UNIQUE (user_id, case_number)
);

CREATE TABLE inspection_result
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT      NOT NULL REFERENCES users (id),
    building_id    BIGINT      NOT NULL REFERENCES building (id),
    case_id        BIGINT REFERENCES cases (id) ON DELETE SET NULL,
    signal_id      BIGINT REFERENCES building_signal (id) ON DELETE SET NULL,
    issue_category VARCHAR(30) NOT NULL,
    outcome        VARCHAR(20) NOT NULL,
    symptoms       JSONB       NOT NULL,
    created_at     TIMESTAMP   NOT NULL
);

CREATE TABLE case_event
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
