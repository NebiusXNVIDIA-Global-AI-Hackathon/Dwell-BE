-- Evidence / File

CREATE TABLE evidence
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id              BIGINT      NOT NULL REFERENCES cases (id) ON DELETE CASCADE,
    user_id              BIGINT      NOT NULL REFERENCES users (id),
    evidence_code        VARCHAR(10) NOT NULL,
    media_type           VARCHAR(10) NOT NULL,
    phase                VARCHAR(20) NOT NULL DEFAULT 'INITIAL',
    location             VARCHAR(20) NOT NULL,
    location_detail      VARCHAR(100),
    sub_location         VARCHAR(20),
    description          VARCHAR(500),
    description_language VARCHAR(10),
    analysis_status      VARCHAR(10) NOT NULL,
    title                VARCHAR(100),
    issue_type           VARCHAR(20),
    severity             VARCHAR(10),
    reasons              JSONB,
    quality_checks       JSONB,
    progression          VARCHAR(10),
    progression_reason   JSONB,
    analyzed_at          TIMESTAMP,
    deleted_at           TIMESTAMP,
    created_at           TIMESTAMP   NOT NULL,
    CONSTRAINT uk_evidence_user_code UNIQUE (user_id, evidence_code)
);

CREATE TABLE repair_verification
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id            BIGINT      NOT NULL REFERENCES cases (id) ON DELETE CASCADE,
    before_evidence_id BIGINT      NOT NULL REFERENCES evidence (id) ON DELETE CASCADE,
    after_evidence_id  BIGINT      NOT NULL REFERENCES evidence (id) ON DELETE CASCADE,
    analysis_status    VARCHAR(10) NOT NULL,
    verdict            VARCHAR(20),
    headline           JSONB,
    summary            JSONB,
    checks             JSONB,
    disclaimer         JSONB,
    confirmed_at       TIMESTAMP,
    created_at         TIMESTAMP   NOT NULL
);

CREATE TABLE file
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id    VARCHAR(20)  NOT NULL UNIQUE,
    user_id      BIGINT       NOT NULL REFERENCES users (id),
    evidence_id  BIGINT REFERENCES evidence (id) ON DELETE SET NULL,
    purpose      VARCHAR(20)  NOT NULL DEFAULT 'EVIDENCE',
    media_type   VARCHAR(10)  NOT NULL,
    mime_type    VARCHAR(50)  NOT NULL,
    size_bytes   BIGINT       NOT NULL,
    duration_sec INT,
    storage_key  VARCHAR(255) NOT NULL,
    sha256       VARCHAR(64)  NOT NULL,
    captured_at  TIMESTAMP,
    quality_ok   BOOLEAN,
    created_at   TIMESTAMP    NOT NULL
);

