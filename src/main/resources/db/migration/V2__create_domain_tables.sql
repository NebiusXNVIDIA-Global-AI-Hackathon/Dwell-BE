    occurred_at TIMESTAMP   NOT NULL,
    title       JSONB,
    ref_type    VARCHAR(20),
    ref_id      BIGINT,
    payload     JSONB,
    alert       BOOLEAN     NOT NULL DEFAULT FALSE
);

CREATE TABLE case_checklist_item
