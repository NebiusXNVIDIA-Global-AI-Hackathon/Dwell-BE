CREATE TABLE reminder
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id     BIGINT      NOT NULL REFERENCES cases (id) ON DELETE CASCADE,
    type        VARCHAR(30) NOT NULL,
    fire_at     TIMESTAMP   NOT NULL,
