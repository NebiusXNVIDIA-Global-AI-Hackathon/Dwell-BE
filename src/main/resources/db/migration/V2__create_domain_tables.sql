CREATE TABLE case_report
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id          BIGINT    NOT NULL REFERENCES cases (id) ON DELETE CASCADE,
    narrative        TEXT      NOT NULL,
